export function getSubServicesByCategory(categorySlug: string): SubService[] {
  return SUB_SERVICES.filter((service) => service.categoryId === categorySlug);
}

export function getSubService(
  categorySlug: string,
  serviceSlug: string
): SubService | undefined {
  return SUB_SERVICES.find(
    (service) =>
      service.categoryId === categorySlug && service.slug === serviceSlug
  );
}

export function getSubServiceById(serviceId: string): SubService | undefined {
  return SUB_SERVICES.find((service) => service.id === serviceId);
}
